CREATE DATABASE IF NOT EXISTS portal_ecl CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE portal_ecl;
CREATE TABLE IF NOT EXISTS cursos (
 id INT AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(150) NOT NULL,descricao TEXT NOT NULL,nivel VARCHAR(40) NOT NULL,ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS pre_inscricoes (
 id INT AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(120) NOT NULL,email VARCHAR(150) NOT NULL,telefone VARCHAR(25),curso_id INT NOT NULL,data_registo DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,estado VARCHAR(30) NOT NULL DEFAULT 'Recebida',
 CONSTRAINT fk_preinscricao_curso FOREIGN KEY(curso_id) REFERENCES cursos(id)
);
CREATE TABLE IF NOT EXISTS utilizadores (
 id INT AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(100) NOT NULL,email VARCHAR(150) NOT NULL UNIQUE,password_hash VARCHAR(255) NOT NULL,perfil ENUM('ADMINISTRADOR','TECNICO') NOT NULL DEFAULT 'TECNICO',ativo BOOLEAN NOT NULL DEFAULT TRUE,data_registo DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS ocorrencias (
 id INT AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(120) NOT NULL,sala VARCHAR(80) NOT NULL,tipo VARCHAR(30) NOT NULL,equipamento VARCHAR(120) NOT NULL,descricao TEXT NOT NULL,data_registo DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,estado ENUM('Por analisar','Em intervenção','A aguardar','Resolvido') NOT NULL DEFAULT 'Por analisar',observacao TEXT
);
